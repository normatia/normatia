"""Response shapes of the Normatia API, as ``TypedDict``: the client returns plain dicts, typed for editors.

Generated by hand from the public OpenAPI (https://docs.normatia.com/openapi.json). Fields the API may add later are
not listed: read them with ``.get()``.
"""
from __future__ import annotations

import sys
from typing import Any, Dict, List, Optional

if sys.version_info >= (3, 11):
    from typing import Literal, TypedDict
else:  # pragma: no cover
    from typing_extensions import Literal, TypedDict

Status = Literal["complete", "partial", "no_data"]


# ── Account ─────────────────────────────────────────────────────────────


class KeyInfo(TypedDict):
    id: str
    mode: Literal["live", "test"]
    name: Optional[str]
    hint: str
    # What the key may do: "data" (reads, free), "ask" (queries, use quota), "mcp" (the MCP server).
    scopes: List[Literal["data", "ask", "mcp"]]
    created_at: str
    last_used_at: Optional[str]


class Quota(TypedDict):
    unlimited: bool
    remaining: Optional[int]
    resets_at: Optional[str]


class RateLimits(TypedDict):
    data_per_minute: int
    intelligence_per_minute: int
    mcp_per_minute: int
    # Data and MCP of the whole organization, adding up all its keys, on top of the key's own limits. A 429 caused by
    # it has ``"group": "organization"`` in the body.
    organization_per_minute: int


class MeResponse(TypedDict):
    key: KeyInfo
    user: Dict[str, Optional[str]]
    organization: Optional[Dict[str, Any]]
    rate_limits: RateLimits
    quota: Quota


class UsageRow(TypedDict):
    calls: int
    credits: int
    errors: int


# ``from`` is a Python keyword: the two dates go in a functional TypedDict.
_UsagePeriod = TypedDict("_UsagePeriod", {"from": str, "to": str})


class UsageResponse(_UsagePeriod):
    scope: Literal["organization", "key"]
    organization_id: Optional[str]
    totals: UsageRow
    by_endpoint: List[Dict[str, Any]]
    by_day: List[Dict[str, Any]]
    this_key: UsageRow
    quota: Quota


class KeyList(TypedDict):
    keys: List[Dict[str, Any]]


# ── Parcels ─────────────────────────────────────────────────────────────


class ConstraintLayer(TypedDict):
    layer: str
    # True affected, False not affected, None no data: None never means "not affected".
    affected: Optional[bool]
    status: Literal["affected", "partially_affected", "context", "not_affected", "no_data"]
    label: Optional[str]
    summary: Optional[str]
    distance_m: Optional[float]
    warnings: List[str]
    # Why there is no data (``no_coverage``) or why it is doubtful.
    reason: Optional[str]
    source: Optional[str]


class ConstraintsSummary(TypedDict):
    affected: int
    context: int
    not_affected: int
    no_data: int


class Constraints(TypedDict):
    summary: ConstraintsSummary
    layers: List[ConstraintLayer]


class Parcel(TypedDict, total=False):
    object: Literal["parcel"]
    ref: str
    place: Dict[str, Optional[str]]
    cadastral_class: Optional[Dict[str, str]]
    main_use: Optional[str]
    area_m2: Optional[float]
    centroid: Optional[Dict[str, float]]
    bbox: Optional[List[float]]
    addresses: List[Dict[str, Any]]
    disclaimer: str
    constraints: Optional[Constraints]
    zoning: Optional[Dict[str, Any]]
    buildings: Optional[Dict[str, Any]]
    units: Optional[Dict[str, Any]]
    geometry: Optional[Dict[str, Any]]


class ParcelAtPoint(TypedDict):
    ref: str
    contains_point: bool
    distance_m: Optional[float]


class ParcelsAtPoint(TypedDict):
    object: Literal["list"]
    # How it was searched: by a point.
    mode: Literal["point"]
    data: List[ParcelAtPoint]
    has_more: bool


class AddressMatch(TypedDict):
    # Whether the candidate matches what was written. None: that part was not written.
    municipality: Optional[bool]
    number: Optional[bool]


class ParcelAtAddress(TypedDict):
    # The cadastral reference of the parcel, 14 characters.
    ref: str
    # The address found: "Calle Mayor 5, Madrid".
    address: Optional[str]
    place: Optional[Dict[str, Optional[str]]]
    # The point of the entrance (portal), {"lat": ..., "lon": ...}.
    location: Optional[Dict[str, float]]
    # "confirmed": the reference is the entrance's; "unconfirmed": an approximation worth checking.
    confidence: Literal["confirmed", "unconfirmed"]
    match: AddressMatch


class AddressInterpretation(TypedDict):
    street: Optional[str]
    number: Optional[str]
    municipality: Optional[str]
    province: Optional[str]


# Why an address search is not exact: "not_understood" (it could not be read as an address) is not "no_candidates" (it
# was understood and does not exist).
AddressSearchReason = Literal[
    "municipality_mismatch", "number_mismatch", "foral_territory", "no_reference", "no_candidates", "ambiguous",
    # No municipality was written: the candidates are those of the largest cities with that street.
    "not_understood", "municipality_missing",
]


class ParcelsAtAddress(TypedDict):
    object: Literal["list"]
    # How it was searched: by an address.
    mode: Literal["address"]
    data: List[ParcelAtAddress]
    has_more: bool
    # True: the address leads to one parcel without doubt. False: pick one in ``data`` or rephrase it.
    exact: bool
    interpreted: Optional[AddressInterpretation]
    # None when ``exact`` is true.
    reason: Optional[AddressSearchReason]
    # Other ways to write the address, when it was not understood.
    suggestions: List[str]


class AddressSuggestion(TypedDict):
    # "street": a street without number (keep typing). "address": an entrance, with its parcel in ``ref``.
    type: Literal["street", "address"]
    # What to show: "Calle Habana, Sudamérica (El Puerto de Santa María)".
    text: str
    place: Optional[Dict[str, Optional[str]]]
    # The province name.
    province: Optional[str]
    postal_code: Optional[str]
    # Only with type "address": the cadastral reference of the entrance's parcel, 14 characters.
    ref: Optional[str]
    location: Optional[Dict[str, float]]


class AddressSuggestions(TypedDict):
    object: Literal["list"]
    data: List[AddressSuggestion]
    has_more: bool


class SandboxInfo(TypedDict):
    object: Literal["sandbox"]
    recorded_at: Optional[str]
    parcels: List[Dict[str, Any]]
    docs_url: str


